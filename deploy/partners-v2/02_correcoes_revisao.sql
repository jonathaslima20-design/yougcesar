/*
  # Partners v2: fixes from the post-implementation review

  1. Internal notes and the owner's CPF/CNPJ were readable by the partner and
     by every agency staff member (the SELECT policy returns whole rows).
     Column privileges now hide `admin_notes` and `document` from client
     roles; the owner reads their own document through my_partner_profile(),
     admins keep reading both through admin_partner_list().
     NOTE: new partner_profiles columns must be added to the GRANT below.

  2. A refund/chargeback reversed "the first commission after the payment"
     with no upper bound, so a payment that never generated a commission
     made the next cycle's (legitimate) commission get reversed. The match
     is now limited to commissions created while that payment could still
     have been approved.

  3. CPF partners above the monthly cap could not withdraw anything. The
     withdrawal now takes the oldest available commissions up to the
     remaining cap (clawbacks always included first).

  4. Suspended partners: commissions keep being recorded, but they are no
     longer released from holding while the suspension lasts (terms: a
     suspension freezes payouts). The admin can reverse them before
     reactivating the partner.
*/

